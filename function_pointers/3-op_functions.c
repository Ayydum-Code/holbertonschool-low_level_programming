#include "3-calc.h"

/**
 * op_add - a function that adds 2 integers
 *
 * @a: integer 1
 * @b: integer 2
 *
 * Return: the sum of a and b
 */
int op_add(int a, int b)
{
	return (a + b);
}

/**
 * op_sub - a function that subtracts 2 integers
 *
 * @a: integer 1
 * @b: integer 2
 *
 * Return: the difference between a and b
 */
int op_sub(int a, int b)
{
	return (a - b);
}

/**
 * op_mul - a function that multiplies 2 integers
 *
 * @a: integer 1
 * @b: integer 2
 *
 * Return: the difference product of a and b
 */
int op_mul(int a, int b)
{
	return (a * b);
}

/**
 * op_div - a function that divides 2 integers
 *
 * @a: integer 1
 * @b: integer 2
 *
 * Return: the difference result of a and b
 */
int op_div(int a, int b)
{
	return (a / b);
}

/**
 * op_mod - a function that returns the remainder
 * of the division between 2 integers
 *
 * @a: integer 1
 * @b: integer 2
 *
 * Return: the remainder of dividing a and b
 */
int op_mod(int a, int b)
{
	return (a % b);
}
